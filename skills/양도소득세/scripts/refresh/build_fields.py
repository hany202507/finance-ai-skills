def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def norm(s):
    return re.sub(r"[\s]", "", s)


def r1(v):
    return round(v, 1)


class Page:
    def __init__(self, page):
        self.p = page
        self.lines = []
        for b in page.get_text("dict")["blocks"]:
            for l in b.get("lines", []):
                s = "".join(sp["text"] for sp in l["spans"])
                if s.strip():
                    self.lines.append((tuple(round(v, 1) for v in l["bbox"]), s))
        self.words = page.get_text("words")
        self.V, self.H, self.shade = [], [], []
        for dr in page.get_drawings():
            fill = dr.get("fill")
            if fill and len(fill) == 3 and max(fill) - min(fill) < 0.02 and 0.3 < fill[0] < 0.95:
                self.shade.append(dr["rect"])
            for it in dr["items"]:
                if it[0] == "l":
                    a, b = it[1], it[2]
                    if abs(a.x - b.x) < 0.6 and abs(a.y - b.y) > 1:
                        self.V.append((a.x, min(a.y, b.y), max(a.y, b.y)))
                    elif abs(a.y - b.y) < 0.6 and abs(a.x - b.x) > 1:
                        self.H.append((a.y, min(a.x, b.x), max(a.x, b.x)))
                elif it[0] == "re":
                    r = it[1]
                    if r.width < 0.8 and r.height > 1:
                        self.V.append((r.x0, r.y0, r.y1))
                    elif r.height < 0.8 and r.width > 1:
                        self.H.append((r.y0, r.x0, r.x1))

    def find(self, label, nth=0, ymin=0, ymax=9999, xmin=0, xmax=9999, exact=False):
        key = norm(label)
        hits = [(bb, s) for bb, s in self.lines
                if (key == norm(s) if exact else key in norm(s))
                and ymin <= bb[1] <= ymax and xmin <= bb[0] <= xmax]
        hits.sort(key=lambda h: (round(h[0][1]), h[0][0]))
        return hits[nth] if len(hits) > nth else None

    def band(self, bb):
        """글자 줄을 감싸는 가로선 두 개(위·아래)."""
        cy = (bb[1] + bb[3]) / 2
        x = bb[2] + 1
        cand = [y for y, x0, x1 in self.H if x0 - 1 <= x <= x1 + 1]
        up = max((y for y in cand if y <= cy - 1), default=None)
        dn = min((y for y in cand if y >= cy + 1), default=None)
        return up, dn

    def cells(self, bb, y0, y1, x_from=None):
        """줄 가운데를 지나는 세로선으로 칸을 나눈다. 라벨 칸 오른쪽부터."""
        if y0 is None or y1 is None:
            return []
        cy = (y0 + y1) / 2
        xs = sorted({round(x, 1) for x, a, b in self.V if a - 0.6 <= cy <= b + 0.6})
        right = max((x1 for y, x0, x1 in self.H if abs(y - y1) < 0.8), default=None)
        if right and (not xs or right > xs[-1] + 2):
            xs.append(round(right, 1))
        start = x_from if x_from is not None else bb[2] - 1
        xs = [x for x in xs if x > start]
        if not xs:
            return []
        # 라벨이 든 칸의 오른쪽 경계부터 값 칸이다
        out = []
        for a, b in zip(xs, xs[1:]):
            if b - a > 4:
                out.append([round(a, 1), round(y0, 1), round(b, 1), round(y1, 1)])
        return out

    def row_right(self, y1):
        return max((x1 for y, x0, x1 in self.H if abs(y - y1) < 0.8), default=None)

    def choices(self, bb, options):
        """「[ ]선택지」 마다 대괄호 안쪽 상자."""
        ws = sorted([w for w in self.words
                     if bb[0] - 1 <= (w[0] + w[2]) / 2 <= bb[2] + 1 and bb[1] - 1 <= (w[1] + w[3]) / 2 <= bb[3] + 1],
                    key=lambda w: w[0])
        out = {}
        for opt in options:
            key = norm(opt)
            for i, w in enumerate(ws):
                if i == 0 or not w[4].startswith("]") or not ws[i - 1][4].endswith("["):
                    continue
                if norm("".join(x[4] for x in ws[i:i + 4]))[1:].startswith(key):
                    lb = ws[i - 1]
                    out[opt] = [r1(lb[2]), r1(min(lb[1], w[1])), r1(w[0]), r1(max(lb[3], w[3]))]
                    break
        return out

    def header_x(self, y0, y1, name):
        """머리 줄(y0~y1)에서 낱말을 이어 붙여 name 이 되는 곳의 가운데 x."""
        ws = sorted([w for w in self.words if y0 <= (w[1] + w[3]) / 2 <= y1], key=lambda w: w[0])
        key = norm(name)
        for i in range(len(ws)):
            s = ""
            for j in range(i, min(i + 6, len(ws))):
                s += norm(ws[j][4])
                if s == key:
                    return (ws[i][0] + ws[j][2]) / 2
                if not key.startswith(s):
                    break
        return None

    def line_region(self, bb):
        """라벨 줄과 같은 줄의 인쇄 글자를 그 칸(좌우 세로선) 안에서 모두 감싸는 상자. 기준점을 찾는 범위다."""
        cy = (bb[1] + bb[3]) / 2
        vs = [x for x, a, b in self.V if a - 0.6 <= cy <= b + 0.6]
        xl = max((x for x in vs if x < bb[0] - 0.5), default=0)
        xr = min((x for x in vs if x > bb[2] + 0.5), default=self.p.rect.width)

        def same(w):
            ov = min(w[3], bb[3]) - max(w[1], bb[1])
            return ov >= 0.5 * min(w[3] - w[1], bb[3] - bb[1])
        ws = [w for w in self.words if w[0] > xl and w[2] < xr and same(w)]
        return [r1(min([w[0] for w in ws] + [bb[0]])), r1(bb[1] - 1.5),
                r1(max([w[2] for w in ws] + [bb[2]])), r1(bb[3] + 1.5)]

    def shaded(self, cell):
        c = pymupdf.Point((cell[0] + cell[2]) / 2, (cell[1] + cell[3]) / 2)
        return any(r.contains(c) for r in self.shade)


def _geo_row(p, bb, f, g):
    y0, y1 = p.band(bb)
    g["행_y"] = [round(y0, 1) if y0 else None, round(y1, 1) if y1 else None]
    g["값_칸"] = p.cells(bb, y0, y1)
    cols = f.get("열")
    cells = g["값_칸"]
    pick = f.pop("열_칸", None)
    if pick:
        out = {}
        for name, i in pick.items():
            a, b = (i, i) if isinstance(i, int) else i
            out[name] = [cells[a][0], cells[a][1], cells[b][2], cells[b][3]]
        g["값_칸_해석"] = out
        g["값_칸_해석_비고"] = "값_칸 순번으로 열을 골랐다(사이 칸은 같은 줄의 다른 라벨)"
    elif cols and len(cells) == len(cols):
        g["값_칸_해석"] = dict(zip(cols, cells))
    elif cols and len(cells) == len(cols) + 1:
        g["값_칸_해석"] = dict(zip(cols, cells[1:]))
        g["값_칸_해석_비고"] = "맨 앞 칸은 이 행에서 쓰지 않는다"
    elif cells:
        g["값_칸_해석"] = {"첫_칸": cells[0]}
        g["값_칸_해석_비고"] = "라벨 바로 오른쪽 칸을 값 칸으로 본다. 뒤 칸들은 같은 줄의 다른 라벨·값이다. 눈으로 확인 필요" if not cols else "칸이 열 수보다 잘게 나뉘어 있다(코드 칸 등 내부 구분선). 눈으로 확인 필요"


def _geo_below(p, bb, f, g):
    up, dn = p.band(bb)
    x = (bb[0] + bb[2]) / 2
    below = [y for y, x0, x1 in p.H if x0 - 1 <= x <= x1 + 1 and y > dn + 1]
    y1 = min(below)
    cells = p.cells(bb, dn, y1, x_from=0)
    g["행_y"] = [r1(dn), r1(y1)]
    g["값_칸"] = cells
    out = {}
    for name in f["열"]:
        cx = p.header_x(up, dn, name)
        cell = next((c for c in cells if cx is not None and c[0] <= cx <= c[2]), None)
        if cell is None:
            raise ValueError("머리 글자 %r 아래 칸을 찾지 못했다" % name)
        out[name] = cell
    g["값_칸_해석"] = out
    g["값_칸_해석_비고"] = "머리 줄 바로 아래 한 줄. 열은 머리 글자 위치로 골랐다"


def _geo_inline(p, bb, f, g):
    y0, y1 = p.band(bb)
    cy = (y0 + y1) / 2
    xs = [x for x, a, b in p.V if a - 0.6 <= cy <= b + 0.6 and x > bb[2] + 0.5]
    xr = min(xs) if xs else p.row_right(y1)
    g["행_y"] = [r1(y0), r1(y1)]
    g["값_칸"] = [[r1(bb[2] + 1), r1(y0), r1(xr), r1(y1)]]
    g["값_칸_해석"] = {"첫_칸": g["값_칸"][0]}
    g["값_칸_해석_비고"] = "라벨과 값이 한 칸에 있다. 라벨 오른쪽부터 그 칸의 오른쪽 세로선까지"


def build(pdf, page_no, meta, spec, out_name, out_dir=None):
    path = os.path.join(FORMS, pdf)
    doc = pymupdf.open(path)
    pg = Page(doc[page_no])
    fields, missing, borrow = [], [], []
    for f in spec:
        f = dict(f)
        lab = f.pop("찾기", None)
        geo = f.pop("geo", "row")
        nth = f.pop("nth", 0)
        rng = f.pop("범위", {})
        exact = f.pop("정확히", False)
        page_override = f.pop("쪽index", None)
        p = pg if page_override is None else Page(doc[page_override])
        f["쪽"] = (page_override if page_override is not None else page_no) + 1
        if lab:
            hit = p.find(lab, nth, exact=exact, **rng)
            if not hit:
                missing.append(f.get("항목명"))
                f["좌표"] = None
            else:
                bb, s = hit
                g = {"라벨_bbox": list(bb), "라벨_원문": s.replace("\uf000", "")}
                if geo == "row":
                    _geo_row(p, bb, f, g)
                elif geo == "below":
                    _geo_below(p, bb, f, g)
                elif geo == "inline":
                    _geo_inline(p, bb, f, g)
                elif geo == "choice":
                    g["값_칸_해석"] = p.choices(bb, f["선택지"])
                    if list(g["값_칸_해석"]) != list(f["선택지"]):
                        raise ValueError("%s 선택지 칸을 다 찾지 못했다: %s" % (f["id"], list(g["값_칸_해석"])))
                    g["값_칸_해석_비고"] = "선택지마다 「[ ]」 안쪽 상자. 고른 칸에 V 를 쓴다"
                elif f.get("기준점"):
                    g["값_칸_해석"] = {"첫_칸": p.line_region(bb)}
                    g["값_칸_해석_비고"] = "인쇄 글자(기준점) 옆에 쓴다. 칸은 기준점을 찾는 범위(같은 줄 인쇄 글자를 그 칸 안에서 감싼 상자)다"
                elif f.get("쓰지않음"):
                    g["값_칸_해석_비고"] = "적지 않는 필드라 칸을 두지 않는다"
                else:
                    g["값_칸_해석_비고"] = "라벨만 찾았다. 값은 라벨 안([ ] 체크, 빈칸 사이) 또는 아래 줄에 쓴다"
                f["좌표"] = g
        if "열_빌림" in f:
            borrow.append((f, f.pop("열_빌림"), p))
        fields.append(f)
    by_id = {f["id"]: f for f in fields}
    for f, b, p in borrow:
        ref = by_id[b["필드"]]["좌표"]["값_칸_해석"]
        y0, y1 = f["좌표"]["행_y"]
        f["좌표"]["값_칸_해석"] = {c: [ref[c][0], y0, ref[c][2], y1] for c in b["열"]}
        f["좌표"]["값_칸_해석_비고"] = "열 경계는 %s 행에서 빌렸다(이 행은 칸이 잘게 나뉘어 있다)" % b["필드"]
    for f in fields:
        g = (f.get("좌표") or {}).get("값_칸_해석") or {}
        p = pg if f["쪽"] == page_no + 1 else Page(doc[f["쪽"] - 1])
        shade = [c for c, cell in g.items() if p.shaded(cell)]
        if shade:
            f["음영_열"] = shade
            if len(shade) == len(g):
                f["음영"] = True
    meta = dict(meta)
    meta["원본파일"] = pdf
    meta["sha256"] = sha256(path)
    meta["쪽수"] = doc.page_count
    meta["쪽크기_pt"] = [round(doc[page_no].rect.width, 1), round(doc[page_no].rect.height, 1)]
    meta["좌표계"] = "PyMuPDF 기준 pt, 원점 왼쪽 위. 값_칸은 [x0,y0,x1,y1]. 라벨 칸 오른쪽의 세로선으로 나눈 칸 목록이며, 표 머리(열 이름)는 '열' 항목을 따른다"
    meta["키"] = {"값_칸_해석": "{열 이름: 칸}. 체크 칸은 열 이름이 선택지다",
                 "기준점": "[{패턴, 쓰는곳(앞·뒤·사이), 부분, 순번, 열}]. 칸 안 인쇄 글자 옆에 쓴다(yangdo/forms_pdf.py)",
                 "음영_열": "회색 채움 칸이라 적지 않는 열. 음영 true 는 모든 열이 음영",
                 "쓰지않음": "신고인이 적지 않는 필드와 그 이유"}
    meta["좌표_못찾음"] = missing
    data = {"meta": meta, "fields": fields}
    with open(os.path.join(out_dir or OUT, out_name), "w", encoding="utf-8") as fp:
        json.dump(data, fp, ensure_ascii=False, indent=1)
    print(out_name, len(fields), "필드, 좌표 못찾음", missing)


