def sheet(out, key):
    p = [f for f in os.listdir(out) if key in f][0]
    return [r for r in openpyxl.load_workbook(os.path.join(out, p)).active.iter_rows(values_only=True)]


def test_build_raw_june():
    out = tempfile.mkdtemp()
    n = G.build_raw(out, tiny(), "2026-06")
    assert sorted(os.listdir(out)) == ["00_전기이월분개장.xlsx", "02_급여대장.xlsx", "03_은행거래내역.xlsx",
                                       "04_카드승인내역.xlsx", "05_세금계산서.xlsx", "06_채널매출.xlsx",
                                       "07_정산차감.xlsx", "거래처마스터.xlsx"]
    ob = sheet(out, "전기이월")
    assert [r[2] for r in ob[1:]] == [103, 213, 331] and ob[2][4:6] == (0, 5) and ob[1][4:6] == (100, 0)
    bank = sheet(out, "은행")
    assert len(bank) == 5 and bank[1][6:8] == ("매출채권회수", "쿠팡") and bank[2][6:8] == ("매출채권회수", "해외바이어")
    assert bank[3][6] == "매입대금결제" and bank[4][6] == "신용카드대금"
    assert all(r[6] != "미분류" for r in bank[1:]), "전기에 있던 거래는 미분류가 아니다"
    ch = sheet(out, "채널매출")
    assert len(ch) == 3      # 머리 + 쿠팡 + 수출. 5월 인보이스는 6월 raw 에 안 들어간다
    assert (ch[1][0], ch[1][1], ch[1][4], ch[1][8], ch[1][11]) == ("2026-06", "COUPANG", "TAXABLE", 1233180, "쿠팡")
    assert (ch[2][1], ch[2][4], ch[2][7], ch[2][8], ch[2][11]) == ("EXPORT", "ZERO", 1, 500000, "해외바이어")
    setl = sheet(out, "정산차감")
    assert setl[1][2:5] == ("판매수수료상계", "쿠팡", 133180)
    tax = sheet(out, "세금계산서")
    assert tax[1][4] == "4623242788" and tax[1][6:9] == (200000, 20000, 220000)
    card = sheet(out, "카드")
    assert card[1][1] == "기업BC" and card[1][5] == "3403735735" and card[1][6] == 1100
    pm = sheet(out, "거래처마스터")
    assert pm[1][0] == "00001" and pm[1][3] == "7374756724"
    assert n["bank"] == 4 and n["payroll"] == 1


def test_전기에_없고_적요가_성격을_안_밝히면_미분류다():
    """미분류 가드레일. 규칙이 100% 를 덮으면 전문가가 검토할 지점이 없어진다.

    적요에 설명 토큰(SWIFT/WIRE/T/T/PAYPAL, 원료대금/제품매입/부자재대금)이 있으면
    신규여도 규칙으로 처리하고, 없으면 가계정으로 보내 목록에 남긴다.
    """
    src = tiny()
    src["bank"] += [
        # 전기에 없고 토큰도 없다. 전문가가 볼 것이다
        {"일련번호": "8", "거래일자": "2026-06-06", "계좌": "주거래", "적요": "해외송금 NEW BUYER LLC",
         "입금액": "700", "출금액": "", "잔액": "0"},
        # 전기에 없지만 토큰이 있다. 규칙으로 처리한다
        {"일련번호": "9", "거래일자": "2026-06-07", "계좌": "주거래", "적요": "WIRE NEW BUYER LLC",
         "입금액": "800", "출금액": "", "잔액": "0"},
    ]
    out = tempfile.mkdtemp()
    G.build_raw(out, src, "2026-06")
    bank = sheet(out, "은행")
    라벨 = {r[4]: r[6] for r in bank[1:]}
    assert 라벨["해외송금 NEW BUYER LLC"] == "미분류", 라벨
    assert 라벨["WIRE NEW BUYER LLC"] == "매출채권회수", 라벨
    assert sum(1 for v in 라벨.values() if v == "미분류") == 1, 라벨
