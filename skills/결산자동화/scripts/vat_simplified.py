# -*- coding: utf-8 -*-
"""간이과세자 부가세 신고 계산 — 공급대가 × 업종별 부가가치율 × 10%.

일반과세와 근본 구조가 다름(매출−매입 아님). 매입은 세금계산서등 수취세액공제(공급대가×0.5%)만.
근거: 부가세법 §63·§69, 시행령 §111②(업종별 부가가치율). 별지 제44호서식(개정 2021.3.16) 원문 검증(2026-07-15).
- 부가가치율 5그룹(소매15/제조20/숙박25/건설30/금융40) = 서식 (5)~(9)와 일치 확인.
- 세금계산서등 수취세액공제 = 공급대가×0.5% (21.7.1 이후 매입 전부, 서식 (15)).
- 의제매입세액공제는 21.7.1부로 간이 폐지(신규거래 미적용).
- 공제세액 합계(㉯)는 매출세액(㉮) 한도(환급 불가). 최종 = ㉮−㉯−예정부과+가산세.
- 납부의무 면제: 연 공급대가 4,800만원 미만(§69).
입력: vat_engine.judge() Judgment 리스트 + 업종.
"""
from dataclasses import dataclass, field
from typing import Dict
from vat_engine import Judgment

# 업종별 부가가치율(%) — 시행령 §111② (2021.7.1.~). 신뢰도 중간(그룹핑 원문 재확인 권장).
간이_부가가치율 = {
    "소매": 15, "음식": 15, "재생용재료": 15,
    "제조": 20, "농림어업": 20, "소화물운송": 20,
    "숙박": 25,
    "건설": 30, "운수창고": 30, "정보통신": 30, "기타서비스": 30,
    "금융보험": 40, "전문과학기술": 40, "사업시설관리": 40, "부동산관련": 40,
}
수취세액공제율 = 5          # /1000 = 0.5% (세금계산서등 수취분 공급대가 기준)
납부의무면제_공급대가 = 48_000_000   # 연 4,800만원 미만 납부의무 면제
발행공제율_2026 = 13        # 1.3%
발행공제한도_2026 = 10_000_000
전자신고세액공제액 = 10_000

# 과세 매출 과세유형(공급대가 집계 대상)
_과세매출 = {11, 14, 17, 22}
# 매입 세금계산서 수취분(수취세액공제 대상)
_매입세계 = {51, 52, 54, 55}


@dataclass
class SimplifiedReturn:
    업종: str
    부가가치율: int
    과세공급대가: int = 0          # 공급가+세액(간이는 공급대가 기준)
    매입세계공급대가: int = 0
    카드발행액: int = 0
    매출세액: int = 0             # 공급대가 × 율 × 10% (㉮)
    수취세액공제: int = 0          # 매입공급대가 × 0.5%
    발행공제: int = 0
    전자신고공제: int = 0
    공제합계: int = 0             # ㉯ (매출세액 한도)
    예정부과세액: int = 0          # ㉱
    가산세: int = 0              # ㉲
    납부의무면제: bool = False
    차감납부: int = 0             # ㉮−㉯−예정부과+가산세


def aggregate_simplified(judgments, 업종, *, 발행공제자격=False, 발행공제_기발생=0,
                         전자신고공제=True, 예정부과세액=0, 가산세=0) -> SimplifiedReturn:
    """간이과세자 세액계산."""
    if 업종 not in 간이_부가가치율:
        raise ValueError(f"미정의 업종: {업종} (간이_부가가치율 참조)")
    율 = 간이_부가가치율[업종]
    r = SimplifiedReturn(업종=업종, 부가가치율=율)
    for j in judgments:
        if j.과세유형 is None:
            continue
        if j.구분 == "매출" and j.과세유형 in _과세매출:
            r.과세공급대가 += j.공급가 + j.세액
            if j.과세유형 in (17, 22):
                r.카드발행액 += j.공급가 + j.세액
        elif j.구분 == "매입" and j.과세유형 in _매입세계:
            r.매입세계공급대가 += j.공급가 + j.세액

    # 매출세액 = 공급대가 × 부가가치율 × 10%
    r.매출세액 = r.과세공급대가 * 율 // 100 * 10 // 100
    # 세금계산서등 수취세액공제 = 매입 공급대가 × 0.5%
    r.수취세액공제 = r.매입세계공급대가 * 수취세액공제율 // 1000
    # 발행공제
    if 발행공제자격:
        raw = r.카드발행액 * 발행공제율_2026 // 1000
        r.발행공제 = max(0, min(raw, 발행공제한도_2026 - 발행공제_기발생))
    r.전자신고공제 = 전자신고세액공제액 if 전자신고공제 else 0
    r.예정부과세액 = 예정부과세액
    r.가산세 = 가산세

    # 납부의무 면제(연 공급대가 4,800만 미만)
    if r.과세공급대가 < 납부의무면제_공급대가:
        r.납부의무면제 = True
        r.차감납부 = 0
        return r
    # 공제세액 합계(㉯)는 매출세액(㉮) 한도 — 환급 불가 구조
    r.공제합계 = min(r.수취세액공제 + r.발행공제 + r.전자신고공제, r.매출세액)
    # 차감납부 = ㉮ − ㉯ − 예정부과 + 가산세 (예정부과 과다 시 (−)환급)
    r.차감납부 = r.매출세액 - r.공제합계 - r.예정부과세액 + r.가산세
    return r
