def _폴더(tmp_path, 끝=7):
    for m in range(1, 끝 + 1):
        연월 = f"2026-{m:02d}"
        (tmp_path / f"급여대장_{연월}.json").write_text(
            json.dumps([_월행(연월)], ensure_ascii=False), encoding="utf-8")
    return tmp_path


def _계약서(경로, 표):
    d = docx.Document()
    d.add_paragraph("근 로 계 약 서")
    d.add_paragraph("제3조 (손해배상) 근로자가 1년 이내에 중도 퇴사하면 교육비 3,000,000원을 배상한다.")
    t = d.add_table(rows=0, cols=2)
    for k, v in 표:
        c = t.add_row().cells
        c[0].text, c[1].text = k, v
    d.save(경로)
    return 경로


