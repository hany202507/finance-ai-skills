def test_고정수당이_통상임금이면_통상임금으로_퇴직금을_낸다():
    # 월급이 전부 고정이면 209시간 기준 일급이 달력 일수 기준 평균임금보다 크다(근기법 §2②, 시행령 §6②4 · ③)
    r = S.퇴직금("2023-09-01", "2026-07-31", 10_800_000, 3_600_000)
    평균기준 = math.ceil(Fraction(10_800_000, 92) * 30 * Fraction(1065, 365))
    통상기준 = math.ceil(Fraction(3_600_000, 209) * 8 * 30 * Fraction(1065, 365))
    assert r["적용"] == "통상임금"
    assert r["평균임금기준"] == 평균기준
    assert r["통상임금기준"] == 통상기준
    assert r["퇴직금"] == 통상기준
    assert 통상기준 > 평균기준


