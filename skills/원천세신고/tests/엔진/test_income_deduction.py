def test_신용카드_문턱_낮은율부터_소진():
    conn = _conn()
    # 총급여 40,000,000 문턱 10,000,000. 신용 10,000,000 + 전통시장 5,000,000
    # 문턱이 신용 전액 소진 → 전통시장 5,000,000×40%=2,000,000이나 추가한도 100만 cap
    자료 = {"부양가족": [{"관계": "본인"}],
           "신용카드": {"신용": 10_000_000, "전통시장": 5_000_000}}
    r = compute(conn, 2025, 자료, 40_000_000)
    assert r.그밖 == 1_000_000


def test_과세표준_파이프라인():
    conn = _conn()
    자료 = {"부양가족": [{"관계": "본인"}], "연금보험료": 2_000_000,
           "건강고용보험료": 1_500_000}
    r = compute(conn, 2025, 자료, 48_000_000)
    assert r.근로소득금액 == 48_000_000 - 근로소득공제(48_000_000)
    assert r.공제계 == 1_500_000 + 2_000_000 + 1_500_000
    assert r.과세표준 == r.근로소득금액 - r.공제계


