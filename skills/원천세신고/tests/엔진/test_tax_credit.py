# -*- coding: utf-8 -*-
"""연말정산 세액공제 테스트 (2025 귀속)."""
import db
from yearend_param import seed_2025
from tax_credit import compute, 근로소득세액공제, 세액공제결과


def _conn():
    conn = db.connect(":memory:"); seed_2025(conn); return conn


def test_근로소득세액공제_한도():
    # 총급여 40,000,000, 산출세액 3,000,000 → 71.5만+(300만-130만)×30%=71.5만+51만=122.5만
    # 한도(3300~7000): 74만−(4000만−3300만)×0.8% = 74만−5.6만=68.4만 → 한도 적용
    v = 근로소득세액공제(40_000_000, 3_000_000)
    assert v == max(660_000, 740_000 - int((40_000_000 - 33_000_000) * 0.008))


def test_자녀세액공제_2025_상향():
    conn = _conn()
    r = compute(conn, 2025, {"자녀세액공제대상": 1}, 40_000_000, 3_000_000)
    assert r.자녀 == 250_000
    r2 = compute(conn, 2025, {"자녀세액공제대상": 2}, 40_000_000, 3_000_000)
    assert r2.자녀 == 550_000
    r3 = compute(conn, 2025, {"자녀세액공제대상": 3}, 40_000_000, 3_000_000)
    assert r3.자녀 == 550_000 + 400_000


def test_의료비_문턱_15퍼센트():
    conn = _conn()
    # 총급여 40,000,000 → 문턱 1,200,000. 일반 3,000,000 → 초과 1,800,000×15%=270,000
    r = compute(conn, 2025, {"의료비": {"일반": 3_000_000}}, 40_000_000, 3_000_000)
    assert r.의료비 == 270_000


def test_의료비_난임_30퍼센트():
    conn = _conn()
    # 난임 2,000,000, 문턱은 일반분 없어 난임에… 문턱 소진 순서상 일반부터인데 일반0 → 남은문턱 난임엔 미적용(우대분 보호)
    # 여기선 일반 5,000,000(문턱소진) + 난임 2,000,000 → 난임 전액 30%
    r = compute(conn, 2025, {"의료비": {"일반": 5_000_000, "난임": 2_000_000}}, 40_000_000, 3_000_000)
    # 일반 5,000,000 − 문턱 1,200,000 = 3,800,000×15%=570,000 + 난임 2,000,000×30%=600,000
    assert r.의료비 == 570_000 + 600_000


