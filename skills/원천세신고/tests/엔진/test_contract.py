# -*- coding: utf-8 -*-
"""근로계약서 검토 테스트."""
from contract_review import 검토

FULL = """임금: 월 3,000,000원(기본급 2,500,000, 식대 200,000, 직책수당 300,000)
지급방법: 매월 25일 근로자 명의 예금계좌 입금
소정근로시간: 09:00~18:00 (휴게 12:00~13:00), 주 40시간
휴일: 매주 일요일(주휴일), 근로자의 날
연차유급휴가: 근로기준법에 따라 부여
취업장소: 서울시 강남구 본사 / 업무: 회계"""


def test_완전한_계약서_이슈없음():
    assert 검토(FULL, "2026-07-01") == []


def test_필수기재_누락_탐지():
    없음 = FULL.replace("연차유급휴가: 근로기준법에 따라 부여", "")
    issues = 검토(없음, "2026-07-01")
    assert any(i.유형 == "필수기재누락" and "연차" in i.항목 for i in issues)
    assert any("§17" in i.근거 for i in issues)


def test_위약예정_금지_탐지():
    위법 = FULL + "\n손해배상: 중도 퇴사 시 위약금 500만원을 배상한다"
    issues = 검토(위법, "2026-07-01")
    위약 = [i for i in issues if i.유형 == "위법조항" and "위약" in i.항목]
    assert 위약
    assert "§20" in 위약[0].근거
    assert 위약[0].대안문구                     # 대안까지 제시


def test_기간제_2년초과_탐지():
    위법 = FULL + "\n계약기간: 3년"
    issues = 검토(위법, "2026-07-01")
    assert any("기간제" in i.항목 for i in issues)


def test_모든_이슈에_근거와_대안():
    위법 = FULL + "\n손해배상: 위약금 500만원\n계약기간: 3년"
    for i in 검토(위법, "2026-07-01"):
        assert i.근거 and i.대안문구


def test_표_형식의_근무_장소와_업무_내용을_찾는다():
    글 = FULL.replace("취업장소: 서울시 강남구 본사 / 업무: 회계", "근무 장소 | 서울 본사\n업무 내용 | 회계")
    assert not any("취업장소" in i.항목 for i in 검토(글, "2026-07-01"))


def test_소정근로시간_칸이_비면_누락이다():
    글 = FULL.replace("소정근로시간: 09:00~18:00 (휴게 12:00~13:00), 주 40시간", "주 소정근로시간 | ")
    이슈 = [i for i in 검토(글, "2026-07-01") if i.항목 == "소정근로시간"]
    assert 이슈 and 이슈[0].현재문구 == "(빈칸)"


def test_수습_3개월_90퍼센트는_위법이_아니다():
    assert not any("수습" in i.항목 for i in 검토(FULL + "\n수습기간: 3개월, 수습 기간 임금은 90% 지급", "2026-07-01"))


def test_수습_6개월은_짚는다():
    assert any("수습" in i.항목 for i in 검토(FULL + "\n수습기간: 6개월", "2026-07-01"))


def test_수습_임금_80퍼센트는_짚는다():
    assert any("수습" in i.항목 for i in 검토(FULL + "\n수습기간 3개월, 임금은 80% 지급", "2026-07-01"))


def test_서면_미교부는_벌금으로_적고_교육비_약정은_판례_기준을_적는다():
    이슈 = {i.항목: i for i in 검토("근로계약서\n제1조 근로자가 1년 이내 중도 퇴사하면 교육비 3,000,000원을 배상한다.\n", "2026-08-01")}
    누락 = [i for i in 이슈.values() if i.유형 == "필수기재누락"]
    assert 누락 and all("과태료" not in i.대안문구 for i in 누락)
    assert all("벌금" in i.대안문구 for i in 누락)
    assert "2006다37274" in 이슈["위약예정 금지"].대안문구
