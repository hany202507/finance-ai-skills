# -*- coding: utf-8 -*-
"""비거주자 원천징수 — 국내세법 기본율 vs 조세조약 제한세율 비교적용.

기본율(소득법 §156①): 사용료·기타 20%. 지방소득세 특별징수 = 소득세×10%.
제한세율 적용 게이트: 거주자증명서 + 수익적소유자. 미비 시 기본율(추후 경정청구 가능).
제한세율이 기본율보다 낮을 때만 적용.

**적재 원칙(중요)**: 조약 원문을 대사한 국가만 TREATY에 넣는다. 추측 세율 금지 —
  세율을 낮게 잘못 넣으면 **과소원천징수 = 납세의무자 리스크**. 미대사국은 기본율로 떨어뜨린다
  (과다원천징수는 경정청구로 회복 가능하나 과소는 가산세).
  원문 대사 경로: korean-law MCP `search_treaties` → `get_treaty_text`.

**사용료는 종류로 세율이 갈린다**: 예) 한·미 협약 §14(1) 일반 15% vs §14(2) 문화적 저작권·
  영화/방송필름 10%. 종류 사실이 없으면 InfoRequest로 물어 확정한다(추정 금지).
"""
from decimal import Decimal, ROUND_DOWN

from withholding_engine import WithholdingResult, InfoRequest, 소득유형

기본율 = {"사용료": Decimal("0.20"), "기타": Decimal("0.20")}

# 사용료 세부구분 코드
사용료_일반 = "일반"                       # 특허·상표·노하우·기술 등
사용료_문화 = "문화적저작권_영화"          # 저작권(문학·연극·음악·예술)·영화/방송용 필름·테이프

# (국가, 소득종류, 세부) → 제한세율. **조약 원문 대사 완료분만**.
TREATY = {
    # 한·미 조세협약(조약 제693호, 발효 1979.10.20) — 원문 대사 2026-07-15
    ("US", "사용료", 사용료_일반): Decimal("0.15"),   # §14(1)
    ("US", "사용료", 사용료_문화): Decimal("0.10"),   # §14(2)
}

# 사용료 세율이 세부구분으로 갈리는 국가 — 사실 없으면 InfoRequest
세부구분_필요 = {("US", "사용료")}

# 원문 미대사 → 기본율. 확충 시 반드시 조약 원문 대사 후 TREATY에 추가할 것.
미대사국_메모 = "JP·CN·DE 등은 조약 원문 미대사 → 기본율 적용. 확충 대상."


def _floor(dec):
    return int(dec.to_integral_value(rounding=ROUND_DOWN))


def _종류키(p):
    return "사용료" if p.소득유형 == 소득유형.사용료 else "기타"


def apply_비거주자(p, on_date):
    """비거주자 지급건 판정. 필요사실은 judge()에서 1차 확인된 상태로 진입."""
    종류 = _종류키(p)
    base = 기본율.get(종류)
    if base is None:
        return InfoRequest(["비거주자 소득종류 확인"],
                           f"비거주자 소득종류 '{p.소득유형}' 기본율 미정의", p.소득유형)

    국가 = p.사실.get("거주지국")
    수익적 = p.사실.get("수익적소유자")
    증명서 = p.사실.get("거주자증명서")

    적용, 적용룰, 서류 = base, "비거주자-국내세법기본율", ""

    조약_적용가능 = 수익적 and 증명서
    if (국가, 종류) in 세부구분_필요 and 조약_적용가능:
        세부 = p.사실.get("사용료구분")
        if 세부 is None:
            return InfoRequest(
                [f"사용료 종류: '{사용료_일반}'(특허·상표·노하우·기술) 또는 "
                 f"'{사용료_문화}'(저작권·영화/방송필름)"],
                f"{국가} 조약상 사용료 제한세율이 종류로 갈림 — 종류 확정 필요",
                p.소득유형)
        treaty = TREATY.get((국가, 종류, 세부))
    else:
        treaty = TREATY.get((국가, 종류, p.사실.get("사용료구분")))

    if treaty is not None and 조약_적용가능 and treaty < base:
        적용 = treaty
        적용룰 = f"조세조약제한세율({국가})"
        서류 = "제한세율적용신청서·거주자증명서 보관"
    elif 국가 and not 증명서:
        서류 = "거주자증명서 미제출 → 기본율 적용(추후 경정청구 가능)"

    소득세 = _floor(Decimal(p.지급총액) * 적용)
    지방소득세 = 소득세 // 10
    근거 = "소득법 §156, 조세조약" + (f" / {서류}" if 서류 else "")
    return WithholdingResult(소득세, 지방소득세, 적용룰, 근거, p.지급총액, p.소득유형)
