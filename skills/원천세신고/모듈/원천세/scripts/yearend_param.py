def _floor(dec):
    return int(dec.to_integral_value(rounding=ROUND_DOWN))


def 근로소득공제(총급여):
    """소득세법 §47 누진 산식. 한도 2,000만원."""
    g = 총급여
    if g <= 5_000_000:
        d = g * 0.70
    elif g <= 15_000_000:
        d = 3_500_000 + (g - 5_000_000) * 0.40
    elif g <= 45_000_000:
        d = 7_500_000 + (g - 15_000_000) * 0.15
    elif g <= 100_000_000:
        d = 12_000_000 + (g - 45_000_000) * 0.05
    else:
        d = 14_750_000 + (g - 100_000_000) * 0.02
    return min(_floor(Decimal(str(d))), 20_000_000)


