def 구분_이름추정(이름):
    n = re.sub(r"[\s()\[\]\-_·.,/]", "", str(이름 or ""))
    if not n:
        return None
    if any(k in n for k in _부채):
        return "부채"
    if any(k in n for k in _자본):
        return "자본"
    # 손익 꼬리말이 자산 말보다 강하다(매출채권처분손실, 유형자산처분이익)
    if n.endswith("손실") or n.endswith("차손"):
        return "비용"
    if n.endswith("이익") or n.endswith("차익"):
        return "수익"
    if n == "개발비":                       # 자산(무형). 경상연구개발비는 비용
        return "자산"
    if any(k in n for k in _자산앞):
        return "자산"
    if "원가" in n:
        return "비용"
    if n.endswith("수수료") and not n.startswith("지급"):
        return None                        # 수수료수입·지급수수료 어느 쪽인지 이름만으로 모른다. 코드대역으로
    if n in ("임대료", "임대료수입") or any(n.endswith(k) for k in _수익꼬리) or "매출" in n:
        return "수익"
    if n.endswith("재료") or n.endswith("원료"):
        return "자산"
    if any(k in n for k in _비용말) or n.endswith("비") or n.endswith("료") or n.endswith("비용"):
        return "비용"
    if any(k in n for k in _자산말):
        return "자산"
    return None


def 구분_코드추정(코드, 이름=None):
    """계정 마스터·재무상태표에 없는 계정의 구분. 이름으로 먼저, 안 되면 더존 표준 코드대역으로 추정한다."""
    g = 구분_이름추정(이름) if 이름 else None
    if g:
        return g
    try:
        c = int(코드)
    except (TypeError, ValueError):
        return None
    if c >= 1000:          # 7자리(2530003)·5자리 코드는 앞 세 자리가 더존 표준 대역이다
        c = int(str(c)[:3])
    if 100 <= c < 250: return "자산"
    if 250 <= c < 330: return "부채"
    if 330 <= c < 400: return "자본"
    if 400 <= c < 450: return "수익"
    if 450 <= c < 900: return "비용"
    if 900 <= c < 930: return "수익"
    if 930 <= c < 1000: return "비용"
    return None


