def 판정(적요, 금액, 정책=None, 거래처=""):
    """반환: dict(활동, 항목, 키워드, 강도) 또는 None. 금액 부호로 입금(+)·출금(-)을 가른다.
    강한 규칙은 적요 글자만 보고, 약한 규칙은 거래처 이름까지 본다."""
    정책 = {**R.정책_기본, **(정책 or {})}
    적 = (적요 or "").strip()
    전체 = f"{적} {거래처 or ''}".strip()
    if not 전체 or not 금액:
        return None
    방향 = "입" if 금액 > 0 else "출"
    for rx, d, 강도, 활, 유입, 유출 in _C:
        if d != "양" and d != 방향:
            continue
        m = rx.search(적 if 강도 == "강" else 전체)
        if not m:
            continue
        if 활.startswith("정책:"):
            활 = 정책[활[3:]]
        return {"활동": 활, "항목": 유입 if 금액 > 0 else 유출, "키워드": m.group(0), "강도": 강도}
    return None
