def test_현금전표의_비현금분은_현금흐름이_아니다():
    """비품 1,000 을 현금 300 + 미지급금 700 으로 샀다. 현금 유출은 300 뿐이고 700 은 비현금 투자 거래다."""
    j = [L("1", 1, 212, 1000, 0, "장비상사"), L("1", 1, 103, 0, 300, "장비상사"), L("1", 1, 253, 0, 700, "장비상사")]
    r = E.실행(j, 전기, 마스터)
    assert r.직접합 == {"영업": 0, "투자": -300, "재무": 0, "환율": 0}
    assert [x["종류"] for x in r.비현금] == ["비현금 투자·재무 거래"]
    assert r.통과
    # 잔금을 치르면 그 700 도 비품 취득으로 추적된다
    j += [L("2", 20, 253, 700, 0, "장비상사"), L("2", 20, 103, 0, 700, "장비상사")]
    r = E.실행(j, 전기, 마스터)
    assert r.직접합["투자"] == -1000 and r.직접합["영업"] == 0 and r.통과


