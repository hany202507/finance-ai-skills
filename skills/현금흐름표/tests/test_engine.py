def test_정산표_비현금_분해(r):
    """감사인 정산표 칸: 감가상각은 누계액 행의 비용가산, 외상 취득은 비품·미지급금 행의 비현금 차대."""
    칸 = r.정산칸
    assert 칸[213]["I"]["감가상각비"] == 20
    assert 칸[212]["W"]["미지급금"] == 1090 and 칸[212]["W"]["가지급금"] == 500
    assert 칸[253]["Y"]["비품"] == 1090 and 칸[134]["Y"]["비품"] == 500
    # 비현금 차변 합계 = 대변 합계
    합 = lambda k: sum(v for c in 칸 for v in 칸[c].get(k, {}).values())
    assert 합("W") == 합("Y")


def test_정산표_행이_설명된다(r):
    """비영업 계정(비품·누계액·차입금·잉여금)은 증감이 비현금분 칸 + 현금분 분류로 남김없이 설명돼야 한다."""
    계 = r.계정
    for c in (212, 213, 260, 375):
        칸 = r.정산칸.get(c, {})
        비현금 = sum(칸.get("I", {}).values()) - sum(칸.get("K", {}).values()) \
            - sum(칸.get("W", {}).values()) + sum(칸.get("Y", {}).values())
        현금분 = sum(t["금액"] for t in r.직접행 if t["상대코드"] == c)
        assert r.m[c] == 비현금 + 현금분, (계[c]["계정"], r.m[c], 비현금, 현금분)


