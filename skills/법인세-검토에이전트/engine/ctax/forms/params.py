class NoValue(KeyError):
    """키는 있는데 그 사업연도에 적용할 값이 없다."""


def keys() -> list:
    return sorted(_P)


def get(key: str, fy_start: str, sme: bool = True):
    """사업연도 개시일(YYYY-MM-DD)에 적용할 값. sme 는 중소기업 여부다."""
    if key not in _P:
        raise KeyError(f"모르는 상수 키: {key}. 쓸 수 있는 키는 {keys()}")
    chosen = None
    for since, v in sorted(_P[key], key=lambda r: r[0]):
        if fy_start >= since:
            chosen = v
    if chosen is None:
        raise NoValue(f"{key} 에 {fy_start} 에 적용할 값이 없다")
    return chosen["sme" if sme else "general"]
