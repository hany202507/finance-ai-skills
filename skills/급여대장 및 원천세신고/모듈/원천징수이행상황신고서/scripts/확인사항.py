# -*- coding: utf-8 -*-
"""대장에서 읽은 행 + 기간/회사 → 확인사항 세 칸 (항목, 왜, 정한 값).

확인사항을 손으로 쓰면 달마다 빠지는 게 달라진다. 8월엔 적었는데 9월엔 안 적는 식이다.
그래서 **조건이 맞으면 반드시 세워지도록** 규칙으로 옮겼다. 정한 값은 대장에서 끌어낼 수
있으면 채우고, 대장 밖의 사실이 필요하면 빈칸으로 둔다 — 빈칸은 엑셀에서 노랗게 칠해진다.

여기 있는 규칙은 「급여대장만 읽으면 반드시 놓치는 것」의 목록이다. 새로 데인 것이 있으면
규칙을 하나 늘려라. 사람의 기억에 맡기지 않는 것이 요점이다.
"""

비과세성항목 = ["식대", "육아수당", "출산지원금", "국외근로수당",
                "연구보조비", "생산직 연장수당", "단체보장성보험료"]
표시명 = {"국외근로수당": "국외근로"}


def _날짜(v):
    """2026-07-31 / datetime → 7/31."""
    if v is None or v == "":
        return ""
    t = str(v)[:10].replace(".", "-").replace("/", "-")
    try:
        _, m, d = t.split("-")[:3]
        return f"{int(m)}/{int(d)}"
    except ValueError:
        return str(v)


def _이라(말):
    """받침이 있으면 「이라」, 없으면 「라」. 자동으로 만든 문장이 어색하면 읽히지 않는다."""
    ch = (말 or " ")[-1]
    if "가" <= ch <= "힣":
        return "이라" if (ord(ch) - 0xAC00) % 28 else "라"
    return "이라"


def _은는(말):
    """받침이 있으면 「은」, 없으면 「는」."""
    return "은" if _이라(말) == "이라" else "는"


def _끝조각(비고):
    """비고의 마지막 조각. 「8일 × 162,000 · 월 1회 지급」의 특기사항은 보통 뒤에 붙는다."""
    t = str(비고 or "").strip()
    if not t:
        return ""
    for 구분 in ("·", "|", ",", ";"):
        if 구분 in t:
            return t.split(구분)[-1].strip()
    return t


def 세우기(행들, 기간, 대장정보=None, 납부주기="매월", 지급항목=(), 전월소득세합=None):
    """조건에 걸리는 확인사항만 만든다. 안 걸리면 안 세운다 — 매달 같은 목록이 나오면
    사람이 읽지 않게 되고, 그러면 진짜로 봐야 할 것도 지나친다."""
    정보 = 대장정보 or {}
    코드별 = {}
    for r in 행들:
        코드별.setdefault(r["소득코드"], []).append(r)
    항목 = []

    # 1. 어느 달 시트를 읽었나 — 노무법인 대장은 달마다 시트가 쌓인다
    시트목록 = 정보.get("시트목록") or []
    if len(시트목록) > 1 and 정보.get("시트"):
        항목.append(("귀속 시트",
                     f"대장에 {'·'.join(시트목록)} 시트가 같이 있습니다",
                     f"{정보['시트']} 시트"))

    # 2. 총지급액에 넣을 비과세 범위 — 달마다 다르게 잡으면 지급명세서와 어긋난다
    면제열 = 정보.get("면제열") or []
    if any(r.get("면제비과세") for r in 행들) and 면제열:
        남는것 = [표시명.get(c, c) for c in 지급항목 if c in 비과세성항목]
        뒤 = f" {'·'.join(남는것)}{_은는(남는것[-1])} 포함" if 남는것 else ""
        항목.append(("총지급액 비과세 처리",
                     "비과세를 포함하되 지급명세서 면제분(시행령 §214①2의2·2의3)만 뺍니다",
                     f"{'·'.join(면제열)}만 제외.{뒤}"))

    # 3. 중도퇴사 정산 — 환급이 나면 소득세가 음수다. 급여대장 본문에는 안 보인다
    for r in 코드별.get("A02", []):
        퇴 = _날짜(r.get("퇴사일"))
        꼬리 = "소득세가 음수" if r["소득세"] < 0 else "정산 세액이 양수"
        항목.append(("중도퇴사자 정산",
                     f"{r['성명']} {퇴} 퇴사. 정산 행이 따로 있고 {꼬리}".replace("  ", " "),
                     f"A02 · {'환급' if r['소득세'] < 0 else '추가납부'} {r['소득세']:,} 그대로"))

    # 4. 퇴직소득 — 서식 작성방법: 연금계좌(A21)란은 연금계좌취급자(금융회사)가 적는다.
    #    회사가 준 퇴직금은 IRP 로 보내도 그 외(A22)에 적는다. IRP 로 이전한 몫은
    #    연금외수령 전까지 원천징수하지 않는다(법 §146②). 이 스킬은 세액을 다시 계산하지
    #    않으므로 세액이 비고와 어긋나면 여기서 짚는다
    연금신호 = ("IRP", "irp", "연금계좌", "과세이연", "이연", "퇴직연금")
    현금신호 = ("현금", "일시금", "직접 수령", "계좌 이체")
    for 코드 in ("A21", "A22"):
        for r in 코드별.get(코드, []):
            비고 = str(r.get("비고") or "")
            이전 = any(m in 비고 for m in 연금신호) and not any(m in 비고 for m in 현금신호)
            이유 = f"{r['성명']} 퇴직금 {r['총지급액']:,} · 퇴직소득세 {r['소득세']:,}"
            if 코드 == "A21":
                이유 += (". A21(연금계좌)란은 연금계좌취급자(금융회사)가 적습니다(서식 작성방법). "
                         "회사가 준 퇴직금이면 IRP 로 보냈어도 A22 로 옮깁니다")
                정함 = ""
            elif 이전 and r["소득세"]:
                이유 += (f". 비고는 「{비고.strip()}」 입니다. IRP 로 이전했으면 연금외수령 전까지 원천징수하지 않으므로"
                         f"(법 §146②) {r['소득세']:,} 원이 걷히지 말았어야 하는 금액인지 봅니다. 이미 걷었으면 환급 신청 대상입니다")
                정함 = ""
            elif 이전:
                정함 = "A22 퇴직소득 그 외. IRP 이전 과세이연이라 소득세 0"
            else:
                정함 = "A22 퇴직소득. 근로에 안 더함"
            항목.append(("퇴직금", 이유, 정함))

    # 5. 일용근로 — 일당 15만원 이하는 세액 0. 0 이 맞는지는 지급 방식까지 봐야 안다
    일용 = 코드별.get("A03", [])
    if 일용:
        낸사람 = [r for r in 일용 if r["소득세"]]
        if 낸사람:
            r = 낸사람[0]
            사유 = _끝조각(r.get("비고"))
            이유 = (f"{r['성명']} {사유}{_이라(사유)} {r['소득세']:,} 원 징수" if 사유
                    else f"{r['성명']} 일당이 15만원을 넘어 {r['소득세']:,} 원 징수")
        else:
            이유 = f"일용 {len(일용)}명 전원 일당 15만원 이하로 세액 0"
        항목.append(("일용직 소득세", 이유, "대장 값 그대로. 0 으로 안 고침"))

    # 6. 기타소득 — 필요경비율이 소득 종류마다 달라 세액이 갈린다
    기타 = [r for c in ("A41", "A42", "A59") for r in 코드별.get(c, [])]
    if 기타:
        항목.append(("기타소득 필요경비",
                     "필요경비율(60%·80%·0%)에 따라 세액이 달라집니다. 대장 값의 근거를 확인합니다",
                     ""))

    # 6-2. 가감계가 음수면 납부세액은 0 이고 그 금액은 ⑮일반환급으로 넘어간다.
    #      자동으로 채우지 않는다 — 환급신청할지 다음 달로 이월할지는 사람이 정한다
    import 집계 as _A
    for 계, 구성 in _A.가감계규칙.items():
        세 = sum(r["소득세"] for c in 구성 for r in 코드별.get(c, []))
        if any(c in 코드별 for c in 구성) and 세 < 0:
            항목.append((f"{_A.소득구분명[계]} 환급 발생",
                         f"{계} 가감계 소득세가 {세:,} 로 음수입니다. ⑩납부세액은 0 이 되고 "
                         f"이 금액은 ⑮일반환급에 적어야 조정·이월로 이어집니다", ""))

    # 7. 전월미환급세액 — 대장에 없다. 전월 신고서를 봐야 안다
    정함 = ""
    if 전월소득세합 is not None and 전월소득세합 >= 0:
        정함 = "없음"
    항목.append(("전월미환급세액",
                 "있으면 신고서 ⑫ 에 넣고 ⑲당월조정환급세액계 까지 이어집니다", 정함))

    # 8. 반기납부 — 반기면 귀속·지급연월 자체가 달라진다
    항목.append(("반기납부 여부", "반기면 귀속·지급연월이 달라집니다", f"{납부주기}납부"))

    # 9. 기한이 밀렸으면 알려준다 (국세기본법 §5① 토·일·공휴일 → 그 다음 날)
    if 기간.get("_이월사유"):
        항목.append(("신고·납부기한",
                     f"법정기한 {기간['_법정기한']} 이 휴일이라 밀렸습니다 (국기법 §5①)",
                     f"{기간['_실제기한']} ({기간['_이월사유']})"))
    return 항목
