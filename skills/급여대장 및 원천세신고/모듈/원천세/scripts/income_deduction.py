# -*- coding: utf-8 -*-
"""연말정산 소득공제 — 인적·연금보험료·특별소득·그밖 + 소득공제 종합한도. 결정론.

근거: 소득세법 §50~§52, 조특법 §126의2(신용카드)·§132의2(종합한도).
부족 사실은 InfoRequest. 앵커 2025 귀속.
"""
from dataclasses import dataclass
from decimal import Decimal, ROUND_DOWN

from withholding_engine import InfoRequest
from yearend_param import 근로소득공제, get_param

# 신용카드등 결제수단별 공제율 (조특법 §126의2). 도서·공연 등은 총급여 7천 이하만.
카드공제율 = {"신용": 0.15, "체크현금": 0.30, "전통시장": 0.40, "대중교통": 0.40,
            "도서공연": 0.30}
# 기본공제 대상(기본한도) vs 추가공제 대상(각 100만 별도한도)
카드_기본대상 = ["신용", "체크현금"]
카드_추가대상 = ["전통시장", "대중교통", "도서공연"]
카드_문화비 = {"도서공연"}          # 총급여 상한 게이트 대상
# 문턱 소진 순서: 공제율 낮은 것부터(납세자 유리) — 신용 → 체크현금 → 나머지
문턱소진순서 = ["신용", "체크현금", "도서공연", "전통시장", "대중교통"]

# 소득공제 종합한도(조특법 §132의2) 대상 — 인적·연금·보험료는 제외
종합한도대상 = ["주택자금", "주택청약", "신용카드", "노란우산"]


@dataclass
class 소득공제결과:
    인적공제: int
    연금보험료: int
    특별소득: int
    그밖: int
    공제전합: int
    종합한도초과: int
    공제계: int
    근로소득금액: int
    과세표준: int


def _floor(x):
    return int(Decimal(x).to_integral_value(rounding=ROUND_DOWN))


def _인적공제(conn, 귀속연도, 부양가족):
    """기본공제 150만/인(소득요건 게이트) + 추가공제. 미확정 사실은 InfoRequest 수집."""
    기본 = get_param(conn, 귀속연도, "기본공제_1인")
    reqs, 합 = [], 0
    for f in 부양가족:
        관계 = f.get("관계")
        if 관계 != "본인":
            if "소득요건충족" not in f:
                reqs.append(f"{관계} 소득요건(연 소득금액 100만/근로만 총급여 500만 이하) 충족 여부")
                continue
            if not f["소득요건충족"]:
                continue
        합 += 기본
        if f.get("경로") or (f.get("나이", 0) >= 70):
            합 += get_param(conn, 귀속연도, "추가공제_경로")
        if f.get("장애"):
            합 += get_param(conn, 귀속연도, "추가공제_장애")
        if f.get("부녀자"):
            합 += get_param(conn, 귀속연도, "추가공제_부녀자")
        if f.get("한부모"):
            합 += get_param(conn, 귀속연도, "추가공제_한부모")
    return 합, reqs


def _신용카드공제(conn, 귀속연도, 총급여, 카드):
    """조특법 §126의2. 문턱(총급여 25%)을 공제율 낮은 것부터 소진 →
    기본대상(신용·체크현금)은 기본한도, 추가대상(전통시장·대중교통·문화비)은 각 100만 별도한도.
    문화비(도서공연 등)는 총급여 상한(7천) 이하만."""
    문턱 = _floor(Decimal(총급여) * get_param(conn, 귀속연도, "신용카드_문턱율") / 100)
    문화비상한 = get_param(conn, 귀속연도, "문화비_총급여상한")
    잔여문턱 = 문턱
    수단별공제 = {}
    for k in 문턱소진순서:
        금액 = 카드.get(k, 0)
        if 금액 <= 0:
            continue
        if k in 카드_문화비 and 총급여 > 문화비상한:
            continue                         # 문화비는 총급여 상한 초과 시 제외
        차감 = min(금액, 잔여문턱)
        잔여문턱 -= 차감
        수단별공제[k] = _floor(Decimal(금액 - 차감) * Decimal(str(카드공제율[k])))

    기본한도 = (get_param(conn, 귀속연도, "카드_기본한도_7천이하")
              if 총급여 <= 70_000_000 else get_param(conn, 귀속연도, "카드_기본한도_7천초과"))
    추가한도 = get_param(conn, 귀속연도, "카드_추가한도")
    기본 = min(sum(수단별공제.get(k, 0) for k in 카드_기본대상), 기본한도)
    추가 = sum(min(수단별공제.get(k, 0), 추가한도) for k in 카드_추가대상)   # 각 100만 별도
    return 기본 + 추가


# 롱테일 공제 — 자료에 없으면 누락되기 쉬운 항목. 확인 미완이면 콕 집어 요청.
롱테일항목 = ["정치자금기부금", "우리사주조합 출연금", "성실사업자 의료비·교육비",
           "장기집합투자증권저축", "청년형장기펀드"]


def compute(conn, 귀속연도, 자료, 총급여):
    """소득공제 산출. 사실 미비 시 InfoRequest 리스트 반환(그 외는 결과)."""
    reqs = []
    부양가족 = 자료.get("부양가족", [{"관계": "본인"}])
    인적, r = _인적공제(conn, 귀속연도, 부양가족)
    reqs += [InfoRequest([s], "부양가족 소득요건 미확정", None) for s in r]

    if 자료.get("롱테일확인미완"):
        reqs.append(InfoRequest(
            [f"해당분 있으면 알려주십시오: {', '.join(롱테일항목)}"],
            "롱테일 공제 누락 방지 — 해당 지출·출연 유무 확인", None))

    연금보험료 = 자료.get("연금보험료", 0)                      # 국민연금 등 전액
    특별소득 = 자료.get("건강고용보험료", 0) + 자료.get("주택자금", 0)
    그밖 = 0
    if 자료.get("신용카드"):
        그밖 += _신용카드공제(conn, 귀속연도, 총급여, 자료["신용카드"])
    그밖 += 자료.get("주택청약", 0) + 자료.get("노란우산", 0)

    if reqs:
        return reqs

    # 소득공제 종합한도(조특법 §132의2): 대상(그밖 + 주택자금)에 적용
    한도대상 = 그밖 + 자료.get("주택자금", 0)
    종합한도 = get_param(conn, 귀속연도, "소득공제_종합한도")
    초과 = max(0, 한도대상 - 종합한도)

    공제전합 = 인적 + 연금보험료 + 특별소득 + 그밖
    공제계 = 공제전합 - 초과
    근로소득금액 = 총급여 - 근로소득공제(총급여)
    과세표준 = max(0, 근로소득금액 - 공제계)
    return 소득공제결과(인적, 연금보험료, 특별소득, 그밖, 공제전합, 초과,
                     공제계, 근로소득금액, 과세표준)
