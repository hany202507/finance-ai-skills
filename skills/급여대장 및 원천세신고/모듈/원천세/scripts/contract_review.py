# -*- coding: utf-8 -*-
"""근로계약서 검토 — 필수기재(근기법 §17) + 위법조항. 결정론 룰.

입력은 계약서 텍스트(docx/pdf 추출은 상위 AI 레이어 — 리스회계 스킬 패턴).
산출은 Issue 리스트. 각 Issue에 근거조문 + **대안문구**까지 — 지적만 하고 끝내지 않는다.
"""
import re
from dataclasses import dataclass


@dataclass
class Issue:
    항목: str
    유형: str        # '필수기재누락' | '위법조항'
    근거: str
    현재문구: str
    대안문구: str


# 필수기재사항 (근기법 §17①) — 항목명 → 탐지 패턴
필수기재 = [
    ("임금 구성항목·계산방법·지급방법", r"(임금|급여|기본급).*(구성|계산|지급)|지급방법|지급일"),
    ("소정근로시간", r"소정근로시간|근로시간"),
    ("휴일(주휴일)", r"휴일|주휴"),
    ("연차유급휴가", r"연차"),
    ("취업장소·종사업무", r"취업\s*장소|근무\s*장소|근무지|업무\s*내용|종사\s*업무|담당\s*업무|업무\s*:"),
]

# 위법조항 룰 — 항목, 탐지패턴, 근거, 대안문구
위법룰 = [
    ("위약예정 금지", r"위약금|손해배상액을?\s*예정|중도\s*퇴사.*배상",
     "근기법 §20 (위약 예정의 금지)",
     "손해를 묻지 않고 정한 금액을 내게 하는 조항은 효력이 없다. 실제 쓴 교육비를 상환하고 일정 기간 근무하면 면제하는 약정은 합리적 범위면 허용된다(대법원 2006다37274). 둘 중 어느 쪽인지 고쳐 쓴다."),
    ("강제 저금", r"강제\s*저축|저금.*강제|예금.*관리한다",
     "근기법 §22 (강제 저금의 금지)",
     "근로자 명의·자유의사에 따른 저축만 가능. 사용자가 관리하는 강제저축 조항 삭제."),
    ("기간제 2년 초과", r"계약기간.*(3|4|5)\s*년|기간제.*[3-9]\s*년",
     "기간제법 §4 (2년 초과 시 무기계약 간주)",
     "기간제 총 사용기간 2년 이내로 조정. 초과 시 무기계약 근로자로 전환됨."),
    ("포괄임금 남용", r"포괄임금|연장.*수당.*포함하여\s*지급.*시간.*미기재",
     "근기법 §56 (가산수당) — 포괄임금은 근로시간 산정이 어려운 경우로 제한",
     "연장·야간·휴일근로 시간을 특정하고 각 가산수당을 구분 기재. 실제 초과분은 추가 지급."),
]



def _을를(말):
    """받침이 있으면 「을」, 없으면 「를」."""
    ch = (말 or " ")[-1]
    return "을" if "가" <= ch <= "힣" and (ord(ch) - 0xAC00) % 28 else "를"

def _찾기(텍스트, 패턴):
    m = re.search(패턴, 텍스트, re.IGNORECASE)
    return m.group(0) if m else None


def 검토(계약서_텍스트, 기준일, *, 사실=None):
    """필수기재 누락 + 위법조항을 탐지해 Issue 리스트 반환. 이슈 없으면 []."""
    t = 계약서_텍스트
    issues = []

    for 항목, 패턴 in 필수기재:
        if 항목 == "소정근로시간" and re.search(r"소정\s*근로\s*시간[^|\n]*\|\s*(\n|$)", t):
            issues.append(Issue(
                항목, "필수기재누락", "근기법 §17 (근로조건의 명시·서면교부)", "(빈칸)",
                "소정근로시간 칸을 채워 서면 교부. 근로시간을 근태로 관리해도 소정근로시간은 정해 둔다."))
            continue
        if not re.search(패턴, t, re.IGNORECASE):
            issues.append(Issue(
                항목, "필수기재누락", "근기법 §17 (근로조건의 명시·서면교부)",
                "(누락)",
                f"'{항목}'{_을를(항목)} 계약서에 명시하고 서면 교부. 위반은 500만원 이하 벌금(근기법 §114)."))

    for 항목, 패턴, 근거, 대안 in 위법룰:
        found = _찾기(t, 패턴)
        if found:
            issues.append(Issue(항목, "위법조항", 근거, found.strip(), 대안))

    수습 = _수습(t)
    if 수습:
        issues.append(Issue("수습 감액 한계", "위법조항",
                            "최저임금법 §5②·시행령 §3 (수습 3개월 이내·최저임금의 90% 이상)", 수습,
                            "수습기간은 3개월 이내, 감액은 최저임금의 90% 이상. 단순노무직은 감액 불가."))
    return issues


def _수습(글):
    """수습 줄에서 3개월을 넘거나 90% 아래인 것만 짚는다. 3개월 90% 는 법이 허용한다."""
    for 줄 in 글.splitlines():
        if "수습" not in 줄:
            continue
        개월 = re.search(r"(\d+)\s*개월", 줄)
        비율 = re.search(r"(\d+)\s*%", 줄)
        if (개월 and int(개월.group(1)) > 3) or (비율 and int(비율.group(1)) < 90):
            return 줄.strip()
    return None
