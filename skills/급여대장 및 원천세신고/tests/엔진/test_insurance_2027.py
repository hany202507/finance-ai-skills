# -*- coding: utf-8 -*-
"""국민연금 근로자 부담률은 해마다 1월 1일에 바뀐다(국민연금법 부칙 <제20903호> 제4조 제1항).

2026년 1만분의 475, 2027년 1만분의 500. 기준소득월액 상한 · 하한은 7월 1일에 바뀌므로(고시) 2026-07-01 구간을
1월 1일에서 한 번 더 나눈다. 2027-07-01 이후 상한 · 하한 고시가 나오기 전에는 계산하지 않고 멈춘다.
"""
import pytest

from insurance_engine import _rates_for, compute


def test_2026년_12월은_475():
    assert _rates_for("2026-12-31")["국민연금"] == 0.0475
    assert compute(3_000_000, "2026-12-31").국민연금 == 142_500


def test_2027년_1월부터_500():
    assert _rates_for("2027-01-01")["국민연금"] == 0.05
    assert compute(3_000_000, "2027-01-01").국민연금 == 150_000


def test_2027년_상반기_상한_하한은_2026년_7월_고시값():
    r = _rates_for("2027-06-30")
    assert (r["국민연금_기준상한"], r["국민연금_기준하한"]) == (6_590_000, 410_000)
    assert compute(10_000_000, "2027-06-30").국민연금 == int(6_590_000 * 0.05)


def test_2027년_7월은_고시가_나오기_전이라_멈춘다():
    with pytest.raises(ValueError, match="요율 미정의"):
        _rates_for("2027-07-01")
