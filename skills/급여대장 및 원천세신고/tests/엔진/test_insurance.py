# -*- coding: utf-8 -*-
"""4대보험 월공제 테스트.

계산 로직은 요율 주입(INJ)으로 데이터와 독립 검증. 2026 스냅샷은 고시 확정 시 갱신.
"""
from insurance_engine import compute, Insurance

# 검증 전용 주입 요율(단순값, 데이터 독립)
INJ = {
    "국민연금": 0.045, "국민연금_기준상한": 6_170_000, "국민연금_기준하한": 390_000,
    "건강보험": 0.03545, "장기요양_건보대비": 0.1295, "고용보험": 0.009,
}


def test_math_with_injected_rates():
    r = compute(3_000_000, "2026-03-01", rates=INJ)
    assert r.국민연금 == 135000        # 300만×4.5%
    assert r.건강보험 == 106350        # 300만×3.545%
    assert r.장기요양 == 13770         # 106350×12.95%=13772.3 → 10원 버림
    assert r.고용보험 == 27000         # 300만×0.9%
    assert r.합계 == 135000 + 106350 + 13770 + 27000


def test_pension_upper_cap():
    r = compute(10_000_000, "2026-03-01", rates=INJ)
    assert r.국민연금 == int(6_170_000 * 0.045)   # 상한 클램프


def test_pension_lower_floor():
    r = compute(300_000, "2026-03-01", rates=INJ)
    assert r.국민연금 == int(390_000 * 0.045)      # 하한 클램프


def test_won_truncation():
    # 1,234,567 × 3.545% = 43765.4 → 43765 (원 미만 절사)
    r = compute(1_234_567, "2026-03-01", rates=INJ)
    assert r.건강보험 == 43760         # 43765.4 → 10원 버림(공단 부과 기준)


def test_non_enrollment_zeroes():
    r = compute(3_000_000, "2026-03-01", rates=INJ, 국민연금가입=False)
    assert r.국민연금 == 0
    assert r.건강보험 > 0


def test_2026_snapshot():
    # 2026 고시(국민연금 4.75%·건강 3.595%·장기요양 13.14%·고용 0.9%)
    r = compute(3_000_000, "2026-03-01")
    assert r.국민연금 == 142500        # 300만×4.75%
    assert r.건강보험 == 107850        # 300만×3.595%
    assert r.장기요양 == 14170         # 107850×13.14%=14171.49 → 10원 버림
    assert r.고용보험 == 27000


def test_국민연금_상한_7월_경계():
    """기준소득월액 상한은 매년 7월 변경 — 2026.6.30 637만 → 2026.7.1 659만."""
    상반기 = compute(10_000_000, "2026-06-30")
    하반기 = compute(10_000_000, "2026-07-01")
    assert 상반기.국민연금 == int(6_370_000 * 0.0475)      # 302,575
    assert 하반기.국민연금 == int(6_590_000 * 0.0475)      # 313,025
    assert 하반기.국민연금 > 상반기.국민연금


def test_국민연금_하한_7월_경계():
    # 하한 40만 → 41만
    assert compute(300_000, "2026-06-30").국민연금 == int(400_000 * 0.0475)
    assert compute(300_000, "2026-07-01").국민연금 == int(410_000 * 0.0475)


def test_상한구간_650만_공단예시_대사():
    """공단 안내: 월 650만이면 2026.7부터 보험료 총 12,350원 증가(본인 6,175원)."""
    전 = compute(6_500_000, "2026-06-30").국민연금
    후 = compute(6_500_000, "2026-07-01").국민연금
    assert 후 - 전 == 6_175                                 # 근로자분 증가
