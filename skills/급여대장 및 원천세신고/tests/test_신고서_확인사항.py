# -*- coding: utf-8 -*-
"""퇴직금 확인사항. 서식 작성방법: 연금계좌(A21)란은 연금계좌취급자(금융회사)가 작성한다.
회사가 준 퇴직금은 IRP 로 보내도 그 외(A22)에 적고, 이전분은 원천징수하지 않는다(소득세법 §146②)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "모듈" / "원천징수이행상황신고서" / "scripts"))
import 확인사항 as K  # noqa: E402


def _퇴직금(코드, 비고, 소득세):
    행 = {"성명": "장가상", "소득코드": 코드, "총지급액": 11_000_000, "소득세": 소득세, "비고": 비고}
    return [x for x in K.세우기([행], {}) if x[0] == "퇴직금"][0]


def test_IRP_이전을_A22_에_세금_0으로_적었으면_그대로_둔다():
    _, 이유, 정함 = _퇴직금("A22", "IRP 이전 · 과세이연(원천징수 안 함, 소득세법 §146②)", 0)
    assert "A22" in 정함 and "과세이연" in 정함


def test_IRP_이전인데_세금을_뗐으면_멈춘다():
    _, 이유, 정함 = _퇴직금("A22", "IRP 이전", 300_000)
    assert 정함 == "" and "§146②" in 이유


def test_회사_행이_A21_이면_A22_로_옮기라고_한다():
    _, 이유, 정함 = _퇴직금("A21", "IRP 이전 · 과세이연", 0)
    assert 정함 == "" and "연금계좌취급자" in 이유 and "A22" in 이유


def test_현금_수령_A22_는_그대로_둔다():
    _, 이유, 정함 = _퇴직금("A22", "퇴직 시 만 58세 · 현금 수령", 250_000)
    assert 정함 == "A22 퇴직소득. 근로에 안 더함"


def test_비과세_포함_문장의_조사가_받침에_맞는다():
    행 = {"성명": "유가상", "소득코드": "A01", "총지급액": 5_600_000, "면제비과세": 200_000, "소득세": 0}
    for 항목, 끝 in ((["식대", "출산지원금"], "출산지원금은 포함"), (["식대", "국외근로수당"], "국외근로는 포함")):
        x = [x for x in K.세우기([행], {}, {"면제열": ["자가운전보조금"]}, 지급항목=항목) if x[0] == "총지급액 비과세 처리"][0]
        assert x[2].endswith(끝), x[2]
