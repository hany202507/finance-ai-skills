import shutil
import sys
from pathlib import Path

import pytest

스킬 = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(스킬 / "scripts"))
import 실행 as X  # noqa: E402

샘플 = 스킬 / "examples" / "샘플회사"

기대 = {  # 코드: (인원, 총지급액, 소득세, 납부세액)
    "A01": (5, 20_100_000, 636_370, 0),
    "A02": (1, 25_200_000, -172_390, 0),
    "A10": (6, 45_300_000, 463_980, 463_980),
    "A20": (1, 12_062_136, 169_490, 169_490),
    "A22": (1, 12_062_136, 169_490, 0),
    "A25": (1, 2_800_000, 84_000, 0),
    "A30": (1, 2_800_000, 84_000, 84_000),
    "A40": (1, 1_000_000, 80_000, 80_000),
    "A59": (1, 1_000_000, 80_000, 0),
    "A99": (9, 61_162_136, 797_470, 797_470),
}


@pytest.fixture(scope="module")
def 끝까지(tmp_path_factory):
    폴더 = tmp_path_factory.mktemp("샘플") / "샘플회사"
    shutil.copytree(샘플, 폴더)
    퇴 = X.퇴사(폴더, "E002", "2026-07-31", 3_600_000)
    기 = X.기타(폴더)
    요약 = X.신고(폴더, "2026-07", 계산값=False)
    return 폴더, 퇴, 기, 요약


def test_퇴직금은_통상임금_기준이_크다(끝까지):
    _, 퇴, _, _ = 끝까지
    assert 퇴["퇴직금"]["적용"] == "통상임금"
    assert 퇴["퇴직금"]["퇴직금"] == 12_062_136
    assert 퇴["퇴직금"]["통상임금기준"] > 퇴["퇴직금"]["평균임금기준"]
    assert 퇴["퇴직소득세"]["징수세액"] == 169_490
    assert [r["소득코드"] for r in 퇴["추가행"]] == ["A02", "A22"]       # 만 57세 · 현금 수령


def test_강연료는_A59_필요경비_60퍼센트(끝까지):
    _, _, 기, _ = 끝까지
    assert 기["연월"] == "2026-07"
    assert [(r["소득코드"], r["소득세"], r["지방소득세"]) for r in 기["추가행"]] == [("A59", 80_000, 8_000)]


def test_소득코드별_표와_납부세액(끝까지):
    _, _, _, 요약 = 끝까지
    assert 요약["종료"] == 0
    assert {c["코드"]: (c["인원"], c["총지급액"], c["소득세"], c["납부세액"]) for c in 요약["소득코드별"]} == 기대
    assert 요약["납부세액"] == 797_470
    assert 요약["위택스_지방소득세"] == 79_760
    assert 요약["기한"] == "2026-08-10"


def test_형식검증_22개를_통과한다(끝까지):
    _, _, _, 요약 = 끝까지
    assert 요약["형식검증"] == {"검사": 22, "통과": 22, "실패": 0}
    assert Path(요약["전자파일"]).name == "20260810C103900.01"


def test_정하지_않은_확인사항이_남는다(끝까지):
    _, _, _, 요약 = 끝까지
    빈 = {x["항목"] for x in 요약["확인사항"] if not x["정한값"]}
    assert {"기타소득 필요경비", "전월미환급세액"} <= 빈


def test_다시_돌려도_같다(끝까지):
    폴더, _, _, 요약 = 끝까지
    다시 = X.신고(폴더, "2026-07", 계산값=False)
    assert 다시["소득코드별"] == 요약["소득코드별"]
    assert Path(다시["전자파일"]).read_bytes() == Path(요약["전자파일"]).read_bytes()
